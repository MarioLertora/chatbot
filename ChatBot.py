print("¡Hola! Bienvenido a nuestra tienda.")

while True:
    print("\nPor favor, elige una de las siguientes opciones:")
    print("1. Polera")
    print("2. Polerón")
    print("3. Gorra")
    print("4. Mochila")

    opcion = input("\nIngresa el número de tu opción: ")

    if opcion == "1":
        producto = "Polera"
        break
    elif opcion == "2":
        producto = "Polerón"
        break
    elif opcion == "3":
        producto = "Gorra"
        break
    elif opcion == "4":
        producto = "Mochila"
        break
    else:
        print("\nOpción no válida. Intenta nuevamente.")

print(f"\nHas seleccionado: {producto}")

direccion = input("\nPor favor, ingresa tu dirección para despacho: ")

print(f"\nConfirmamos que tu dirección de despacho es: {direccion}")
print(f"Tu pedido de {producto} será despachado a esa dirección.")

print("\nMuchas gracias por tu compra.")
print("¡Que tengas un excelente día!")